<?php

require_once __DIR__ . '/bootstrap.php';

// Only authenticated administrators may manage manually recorded payments.
if (empty($_SESSION['user_id']) || ($_SESSION['user_role'] ?? '') !== 'admin') {
    jsonResponse(false, 'Administrator access required.', [], 403);
}

requirePost();
$data = getJsonInput();
$action = strtolower(trim((string) ($data['action'] ?? '')));

function meterlyPaymentIsPaystackVerified(array $payment): bool
{
    $method = strtolower(trim((string) ($payment['payment_method'] ?? '')));
    $reference = strtoupper(trim((string) ($payment['transaction_reference'] ?? '')));

    // Paystack references generated by Meterly use the MTR_ prefix.
    return $method === 'paystack' || str_starts_with($reference, 'MTR_');
}

function meterlyRecalculateBillStatus(PDO $pdo, int $billId): void
{
    $stmt = $pdo->prepare(
        "UPDATE bills AS b
         SET status = CASE
             WHEN (
                 SELECT COALESCE(SUM(p.amount), 0)
                 FROM payments p
                 WHERE p.bill_id = b.id
                   AND LOWER(p.payment_status) = 'successful'
             ) >= b.amount THEN 'paid'
             WHEN b.due_date < CURDATE() THEN 'overdue'
             ELSE 'unpaid'
         END
         WHERE b.id = ?"
    );
    $stmt->execute([$billId]);
}

try {
    if (!in_array($action, ['create', 'update', 'delete'], true)) {
        jsonResponse(false, 'Invalid payment action.', [], 422);
    }

    if ($action === 'delete' || $action === 'update') {
        $id = filter_var($data['id'] ?? null, FILTER_VALIDATE_INT);
        if (!$id || $id < 1) {
            jsonResponse(false, 'Invalid payment ID.', [], 422);
        }

        $find = $pdo->prepare(
            'SELECT id, bill_id, amount, payment_method, payment_status, transaction_reference
             FROM payments
             WHERE id = ?
             LIMIT 1'
        );
        $find->execute([$id]);
        $existing = $find->fetch(PDO::FETCH_ASSOC);

        if (!$existing) {
            jsonResponse(false, 'Payment record not found.', [], 404);
        }

        if (meterlyPaymentIsPaystackVerified($existing)) {
            jsonResponse(
                false,
                'This transaction was verified by Paystack and is protected. It cannot be edited or deleted.',
                [],
                403
            );
        }
    }

    if ($action === 'delete') {
        $pdo->beginTransaction();
        $delete = $pdo->prepare(
            "DELETE FROM payments
             WHERE id = ?
               AND (payment_method IS NULL OR LOWER(payment_method) <> 'paystack')
               AND (transaction_reference IS NULL OR LEFT(transaction_reference, 4) <> 'MTR_')"
        );
        $delete->execute([$id]);

        if ($delete->rowCount() !== 1) {
            $pdo->rollBack();
            jsonResponse(false, 'Payment could not be deleted. Verified Paystack transactions are protected.', [], 403);
        }

        meterlyRecalculateBillStatus($pdo, (int) $existing['bill_id']);
        $pdo->commit();
        jsonResponse(true, 'Manual payment record deleted successfully.');
    }

    $billId = filter_var($data['bill_id'] ?? null, FILTER_VALIDATE_INT);
    $amount = $data['amount'] ?? null;
    $method = trim((string) ($data['payment_method'] ?? ''));
    $status = strtolower(trim((string) ($data['payment_status'] ?? '')));

    if (!$billId || $billId < 1) {
        jsonResponse(false, 'Select a valid bill.', [], 422);
    }

    if (!is_numeric($amount) || !is_finite((float) $amount) || (float) $amount <= 0) {
        jsonResponse(false, 'Enter a valid payment amount.', [], 422);
    }

    $allowedMethods = ['Bank transfer', 'Card', 'Cash', 'Other'];
    if (!in_array($method, $allowedMethods, true)) {
        jsonResponse(false, 'Paystack transactions are created only by verified Paystack checkout. Select a manual payment method.', [], 422);
    }

    $allowedStatuses = ['pending', 'successful', 'failed'];
    if (!in_array($status, $allowedStatuses, true)) {
        jsonResponse(false, 'Select a valid payment status.', [], 422);
    }

    $billCheck = $pdo->prepare('SELECT id FROM bills WHERE id = ? LIMIT 1');
    $billCheck->execute([$billId]);
    if (!$billCheck->fetchColumn()) {
        jsonResponse(false, 'Selected bill does not exist.', [], 404);
    }

    if ($action === 'create') {
        $reference = 'ADM_' . strtoupper(bin2hex(random_bytes(12)));

        $pdo->beginTransaction();
        $insert = $pdo->prepare(
            'INSERT INTO payments
             (bill_id, amount, payment_method, payment_status, transaction_reference, payment_date)
             VALUES (?, ?, ?, ?, ?, NOW())'
        );
        $insert->execute([$billId, $amount, $method, $status, $reference]);

        meterlyRecalculateBillStatus($pdo, (int) $billId);
        $newId = (int) $pdo->lastInsertId();
        $pdo->commit();

        jsonResponse(true, 'Manual payment recorded successfully.', [
            'payment_id' => $newId,
            'reference' => $reference
        ], 201);
    }

    // Update is limited to manual records; the Paystack guard above is repeated
    // in the SQL predicate to protect against a concurrent change.
    $oldBillId = (int) $existing['bill_id'];
    $pdo->beginTransaction();
    $update = $pdo->prepare(
        "UPDATE payments
         SET bill_id = ?,
             amount = ?,
             payment_method = ?,
             payment_status = ?,
             payment_date = NOW()
         WHERE id = ?
           AND (payment_method IS NULL OR LOWER(payment_method) <> 'paystack')
           AND (transaction_reference IS NULL OR LEFT(transaction_reference, 4) <> 'MTR_')"
    );
    $update->execute([$billId, $amount, $method, $status, $id]);

    if ($update->rowCount() === 0) {
        // A no-op update is valid only if the record still exists and is manual.
        $confirm = $pdo->prepare(
            "SELECT payment_method, transaction_reference
             FROM payments WHERE id = ? LIMIT 1"
        );
        $confirm->execute([$id]);
        $current = $confirm->fetch(PDO::FETCH_ASSOC);
        if (!$current || meterlyPaymentIsPaystackVerified($current)) {
            $pdo->rollBack();
            jsonResponse(false, 'Verified Paystack transactions are protected and cannot be edited.', [], 403);
        }
    }

    meterlyRecalculateBillStatus($pdo, $oldBillId);
    if ((int) $billId !== $oldBillId) {
        meterlyRecalculateBillStatus($pdo, (int) $billId);
    }
    $pdo->commit();

    jsonResponse(true, 'Manual payment record updated successfully.');

} catch (Throwable $e) {
    if ($pdo->inTransaction()) {
        $pdo->rollBack();
    }

    error_log('Meterly admin payment management error: ' . $e->getMessage());
    jsonResponse(false, 'The payment record could not be saved. Please check the bill and payment details.', [], 500);
}
